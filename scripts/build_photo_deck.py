def main() -> None:
    page_records = {item["page"]: item for item in json.loads(PAGE_INDEX.read_text(encoding="utf-8"))}
    photo_records = json.loads(ALL_PHOTOS.read_text(encoding="utf-8"))
    by_page = {}
    PUBLIC_PHOTOS.mkdir(parents=True, exist_ok=True)
    for existing in PUBLIC_PHOTOS.glob("*.jpg"):
        try:
            existing_page = int(existing.name[1:4])
        except ValueError:
            continue
        if existing_page not in PAGE_RANGE:
            existing.unlink()
    for record in photo_records:
        if record["page"] not in PAGE_RANGE:
            continue
        source = ROOT / record["file"]
        if source.name in {"p046-img01-f9c3e2b346.png", "p046-img03-4a6534fc1e.png", "p046-img05-a4294c8f8a.png", "p046-img07-2cdbd2db47.png", "p046-img09-a70a330982.png"}:
            continue
        try:
            with Image.open(source) as image:
                rgba = image.convert("RGBA").resize((48, 48))
                pixels = list(rgba.getdata())
                visible = sum(pixel[3] > 8 for pixel in pixels) / len(pixels)
                brightness = sum(ImageStat.Stat(rgba.convert("RGB")).mean) / 3
                if visible < 0.78 or brightness < 8:
                    continue
                target_name = f"p{record['page']:03d}-img{record['index']:02d}.jpg"
                target = PUBLIC_PHOTOS / target_name
                image.convert("RGB").save(target, "JPEG", quality=92, optimize=True)
                by_page.setdefault(record["page"], []).append({**record, "publicFile": f"assets/photo-pages/photos/{target_name}"})
        except Exception:
            continue
    PUBLIC_IMAGES.mkdir(parents=True, exist_ok=True)
    deck = []
    for page in PAGE_RANGE:
        source = page_records.get(page)
        if not source or source["embedded_images"] < 4 or page not in THEMES:
            continue
        page_image = PAGE_IMAGES / f"page-{page:03d}.jpg"
        public_image = PUBLIC_IMAGES / page_image.name
        shutil.copy2(page_image, public_image)
        title, summary, analysis, notes = THEMES[page]
        photos = []
        for index, record in enumerate(sorted(by_page.get(page, []), key=lambda item: item["index"]), start=1):
            category_text = {"sport-international": "運動與國際行動", "character-care": "品格與陪伴行動", "reading-vision": "閱讀與教育願景", "innovation-community": "科技與學習社群", "leadership": "團隊與教育領導", "profile-awards": "人物與教育成果"}.get(source["category"], "教育現場")
            photos.append({**record, "slideCaption": f"第 {index} 張｜{category_text}：{title}中的現場紀錄｜原簡報第 {page} 頁"})
        deck.append({"page": page, "title": title, "summary": summary, "analysis": analysis, "speakerNotes": notes, "themeCategory": source["category"], "overviewImage": f"assets/photo-pages/{page_image.name}", "photoCount": len(photos), "photos": photos})
    OUTPUT.write_text(json.dumps(deck, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"built {len(deck)} photo themes")
    print(f"photos indexed in themes: {sum(item['photoCount'] for item in deck)}")


